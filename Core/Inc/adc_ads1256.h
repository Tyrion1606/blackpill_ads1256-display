#ifndef ADC_ADS1256_H
#define ADC_ADS1256_H

#include "main.h"
#include <stdint.h>

/* =========================
 * PINAGEM DO ADC ADS1256
 * ========================= */
#define ADC_ADS1256_CHIP_SELECT_GPIO_PORT ADS_CS_GPIO_Port
#define ADC_ADS1256_CHIP_SELECT_GPIO_PIN  ADS_CS_Pin

#define ADC_ADS1256_DATA_READY_GPIO_PORT  ADS_DRDY_GPIO_Port
#define ADC_ADS1256_DATA_READY_GPIO_PIN   ADS_DRDY_Pin

#define ADC_ADS1256_POWER_DOWN_GPIO_PORT  ADS_PDWN_GPIO_Port
#define ADC_ADS1256_POWER_DOWN_GPIO_PIN   ADS_PDWN_Pin

/* =========================
 * COMANDOS DO ADC ADS1256
 * ========================= */
#define ADC_ADS1256_COMMAND_WAKEUP         0x00U
#define ADC_ADS1256_COMMAND_READ_DATA      0x01U
#define ADC_ADS1256_COMMAND_READ_DATA_CONT 0x03U
#define ADC_ADS1256_COMMAND_STOP_READ_CONT 0x0FU
#define ADC_ADS1256_COMMAND_READ_REGISTER  0x10U
#define ADC_ADS1256_COMMAND_WRITE_REGISTER 0x50U
#define ADC_ADS1256_COMMAND_SELF_CAL       0xF0U
#define ADC_ADS1256_COMMAND_SYNC           0xFCU
#define ADC_ADS1256_COMMAND_STANDBY        0xFDU
#define ADC_ADS1256_COMMAND_RESET          0xFEU

/* =========================
 * REGISTRADORES DO ADC ADS1256
 * ========================= */
#define ADC_ADS1256_REGISTER_STATUS 0x00U
#define ADC_ADS1256_REGISTER_MUX    0x01U
#define ADC_ADS1256_REGISTER_ADCON  0x02U
#define ADC_ADS1256_REGISTER_DRATE  0x03U

/* =========================
 * TAXAS DE AMOSTRAGEM DO ADC ADS1256
 * ========================= */
#define ADC_ADS1256_DATA_RATE_30000_SAMPLES_PER_SECOND 0xF0U
#define ADC_ADS1256_DATA_RATE_15000_SAMPLES_PER_SECOND 0xE0U
#define ADC_ADS1256_DATA_RATE_7500_SAMPLES_PER_SECOND  0xD0U
#define ADC_ADS1256_DATA_RATE_2000_SAMPLES_PER_SECOND  0xB0U
#define ADC_ADS1256_DATA_RATE_1000_SAMPLES_PER_SECOND  0xA1U
#define ADC_ADS1256_DATA_RATE_100_SAMPLES_PER_SECOND   0x82U
#define ADC_ADS1256_DATA_RATE_10_SAMPLES_PER_SECOND    0x23U
#define ADC_ADS1256_DATA_RATE_2_5_SAMPLES_PER_SECOND   0x03U

#define ADC_ADS1256_SELECTED_DATA_RATE ADC_ADS1256_DATA_RATE_1000_SAMPLES_PER_SECOND

/*
 * Throughput estimado para ciclagem do MUX com fCLKIN = 7.68MHz.
 * Valores em decimos para evitar ponto flutuante no firmware.
 */
#if ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_30000_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10             300000U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10   43740U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_15000_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10             150000U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10   38170U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_7500_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10              75000U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10   30430U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_2000_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10              20000U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10   14380U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_1000_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10              10000U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10    8370U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_100_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10               1000U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10     980U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_10_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10                100U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10     100U
#elif ADC_ADS1256_SELECTED_DATA_RATE == ADC_ADS1256_DATA_RATE_2_5_SAMPLES_PER_SECOND
#define ADC_ADS1256_SELECTED_DATA_RATE_SPS_X10                 25U
#define ADC_ADS1256_SELECTED_CYCLING_READS_PER_SECOND_X10      25U
#else
#error "ADC_ADS1256_SELECTED_DATA_RATE sem informacao de throughput de ciclagem"
#endif

/* =========================
 * TAXAS DE GANHO(PGA) DO ADC ADS1256
 * ========================= */
#define ADC_ADS1256_PGA_GAIN_1   0x00U
#define ADC_ADS1256_PGA_GAIN_2   0x01U
#define ADC_ADS1256_PGA_GAIN_4   0x02U
#define ADC_ADS1256_PGA_GAIN_8   0x03U
#define ADC_ADS1256_PGA_GAIN_16  0x04U
#define ADC_ADS1256_PGA_GAIN_32  0x05U
#define ADC_ADS1256_PGA_GAIN_64  0x06U

#define ADC_ADS1256_SELECTED_PGA_GAIN ADC_ADS1256_PGA_GAIN_1

/* =========================
 * CANAIS DO MUX DO ADC ADS1256
 * =========================
 *
 * MUX = PSEL[3:0] no nibble alto e NSEL[3:0] no nibble baixo.
 * AINCOM e selecionado com 0x8 no nibble correspondente.
 *
 * Para medicoes diferenciais, o datasheet recomenda usar entradas adjacentes
 * AIN0..AIN7, preferencialmente em pares como AIN0-AIN1.
 */
#define ADC_ADS1256_CHANNEL_AIN0_AGAINST_AINCOM 0x08U

#define ADC_ADS1256_CHANNEL_AIN0_AGAINST_AIN1   0x01U
#define ADC_ADS1256_CHANNEL_AIN2_AGAINST_AIN3   0x23U
#define ADC_ADS1256_CHANNEL_AIN4_AGAINST_AIN5   0x45U
#define ADC_ADS1256_CHANNEL_AIN6_AGAINST_AIN7   0x67U

#define ADC_ADS1256_SELECTED_CHANNEL ADC_ADS1256_CHANNEL_AIN0_AGAINST_AIN1

#define ADC_ADS1256_DIFFERENTIAL_CHANNEL_COUNT 4U

typedef struct
{
  uint8_t muxRegisterValue;
  const char *name;
} AdcADS1256_ChannelConfig;

extern const AdcADS1256_ChannelConfig AdcADS1256_DifferentialChannels[ADC_ADS1256_DIFFERENTIAL_CHANNEL_COUNT];

void AdcADS1256_SetPinsToSafeState(void);
void AdcADS1256_Initialize(void);
void AdcADS1256_WaitUntilDataIsReady(void);
int32_t AdcADS1256_ReadRawSigned24BitValueContinuousMode(void);
int32_t AdcADS1256_ReadRawSigned24BitValueFromChannel(uint8_t muxRegisterValue);
uint8_t AdcADS1256_ReadSingleRegister(uint8_t registerAddress);

#endif /* ADC_ADS1256_H */
